export type Status = 'done' | 'current' | 'next'

export interface Stage {
  /** Номер этапа, по порядку */
  id: number
  /** Название этапа */
  title: string
  /** Уточнение под названием (необязательно) */
  subtitle?: string
  status: Status
  /** Первый день этапа: '12.11'. Пусто, если дата не определена */
  date: string
  /** Последний день, если этап длится несколько дней: '16.11' */
  dateEnd?: string
  /** Что делаем */
  what: string
  /** Зачем */
  why: string
  /** Что получит клиника. Пусто, если нечего сказать */
  result: string
}

export interface AccessItem {
  title: string
  received: boolean
}

